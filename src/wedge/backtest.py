"""Walk-forward backtest. Each week is forecast as of its Tuesday decision time by a model
trained only on weeks whose actuals EIA had already released by then.

Features come from features.build_many, which is point-in-time per target, and the training
filter here uses the same release calendar, so neither inputs nor labels can leak.
"""

from collections.abc import Callable
from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path

import pandas as pd

from wedge import config, features, metrics, releases
from wedge.models import PRED_COLUMNS, Model

REFERENCE = "seasonal_5y"
WARMUP_YEARS = 6  # features and errors need history before the first test week
REPORT_DIR = config.REPO_ROOT / "reports" / "backtest"


def fridays(start: date, end: date) -> list[date]:
    first = start + timedelta(days=(releases.FRIDAY - start.weekday()) % 7)
    return [first + timedelta(weeks=i) for i in range((end - first).days // 7 + 1)]


def dataset(wide: pd.DataFrame, targets: list[date]) -> tuple[pd.DataFrame, pd.Series]:
    """Point-in-time features and realised changes; weeks without an actual are dropped."""
    y = pd.Series([features.actual_change(wide, t) for t in targets], index=targets, name="actual")
    y = y.dropna()
    X = features.build_many(wide, list(y.index))
    return X, y


def walk_forward(
    factory: Callable[[], Model],
    X: pd.DataFrame,
    y: pd.Series,
    test_targets: list[date],
    refit_every: int = 1,
) -> pd.DataFrame:
    """Predictions for each test target; refit every `refit_every` test weeks."""
    released = pd.Series([releases.release_time(t) for t in X.index], index=X.index)
    rows = []
    model = None
    for i, target in enumerate(test_targets):
        if target not in X.index:
            continue
        if model is None or i % refit_every == 0:
            as_of = releases.decision_time(target)
            train = X.index[(released <= as_of).to_numpy() & (X.index < target)]
            train = train.intersection(y.index)
            model = factory()
            model.fit(X.loc[train], y.loc[train])
        rows.append(model.predict(X.loc[[target]]))
    if not rows:
        raise ValueError("no test targets with features")
    pred = pd.concat(rows)[PRED_COLUMNS]
    pred.index.name = "target"
    return pred


@dataclass
class BacktestResult:
    predictions: dict[str, pd.DataFrame]
    actuals: pd.Series

    def summary(self, start: date | None = None, end: date | None = None) -> pd.DataFrame:
        y = self.actuals.loc[start:end]
        ref = self.predictions.get(REFERENCE)
        ref_mae = metrics.score(ref.loc[start:end], y)["mae"] if ref is not None else None
        table = {
            name: metrics.score(pred.loc[start:end], y, ref_mae)
            for name, pred in self.predictions.items()
        }
        return pd.DataFrame(table).T

    def mae_by_year(self) -> pd.DataFrame:
        cols = {}
        for name, pred in self.predictions.items():
            err = (self.actuals - pred["point"]).dropna().abs()
            cols[name] = err.groupby([t.year for t in err.index]).mean()
        return pd.DataFrame(cols)


def run(
    wide: pd.DataFrame,
    start: date,
    end: date,
    models: dict[str, Callable[[], Model]],
    refit_every: int = 1,
) -> BacktestResult:
    test = fridays(start, end)
    history = fridays(date(start.year - WARMUP_YEARS, 1, 1), end)
    history = [t for t in history if t in wide.index]
    X, y = dataset(wide, history)
    preds = {
        name: walk_forward(factory, X, y, test, refit_every) for name, factory in models.items()
    }
    return BacktestResult(preds, y.loc[test[0] : test[-1]])


def _fmt(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()
    for col in ["mae", "rmse", "bias", "pinball"]:
        if col in out:
            out[col] = (out[col] / 1000).map("{:.2f}".format)
    for col in ["hit_rate", "coverage_80", "skill"]:
        if col in out:
            out[col] = out[col].map("{:.1%}".format)
    if "brier" in out:
        out["brier"] = out["brier"].map("{:.3f}".format)
    if "n" in out:
        out["n"] = out["n"].astype(int)
    return out


def render_markdown(result: BacktestResult, start: date, end: date, title: str) -> str:
    sel_start = date(max(start.year, 2022), 1, 1)
    lines = [
        f"# {title}",
        "",
        f"Walk-forward, {start} to {end}: each week forecast as of Tuesday 18:00 ET using only "
        "data released by then. Errors and losses in million barrels (mb). Skill = 1 - MAE / "
        f"MAE of `{REFERENCE}`. Intervals and P(build) come from each model's trailing "
        "156-week errors. Generated by `wedge backtest`; do not edit by hand.",
        "",
        "## Full period",
        "",
        _fmt(result.summary()).to_markdown(),
        "",
        f"## Selection window ({sel_start} onward, ADR 0005)",
        "",
        _fmt(result.summary(sel_start)).to_markdown(),
        "",
        "## MAE by year (mb)",
        "",
        (result.mae_by_year() / 1000).round(2).to_markdown(),
        "",
    ]
    return "\n".join(lines)


def write_report(result: BacktestResult, name: str, start: date, end: date, title: str) -> Path:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    md = REPORT_DIR / f"{name}.md"
    md.write_text(render_markdown(result, start, end, title), encoding="utf-8")
    preds = pd.concat(result.predictions, names=["model"]).reset_index()
    preds = preds.merge(result.actuals.reset_index().rename(columns={"index": "target"}))
    preds.round({c: 1 for c in PRED_COLUMNS if c != "p_build"} | {"p_build": 4}).to_csv(
        REPORT_DIR / f"{name}_predictions.csv", index=False, lineterminator="\n"
    )
    return md
